type D2D1_COLOR_F struct {
	r FLOAT
	g FLOAT
	b FLOAT
	a FLOAT
}

const (
	sc_redShift   UINT32 = 16
	sc_greenShift UINT32 = 8
	sc_blueShift  UINT32 = 0
)

const (
	sc_redMask   UINT32 = 0xff << sc_redShift
	sc_greenMask UINT32 = 0xff << sc_greenShift
	sc_blueMask  UINT32 = 0xff << sc_blueShift
)

func D2D1_ColorF(rgb UINT32) (cf D2D1_COLOR_F) {
	return D2D1_COLOR_F{
		r: FLOAT((rgb&sc_redMask)>>sc_redShift) / 255.0,
		g: FLOAT((rgb&sc_greenMask)>>sc_greenShift) / 255.0,
		b: FLOAT((rgb&sc_blueMask)>>sc_blueShift) / 255.0,
		a: FLOAT(1.0),
	}
}
